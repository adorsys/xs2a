package de.adorsys.psd2.xs2a.service;

import de.adorsys.psd2.xs2a.core.security.SecuringBodyMessage;
import de.adorsys.psd2.xs2a.core.security.SigningHttpMessage;
import lombok.RequiredArgsConstructor;
import org.apache.commons.lang3.BooleanUtils;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;
import org.springframework.stereotype.Service;

import jakarta.servlet.http.HttpServletRequest;
import java.util.Optional;
import java.util.UUID;

/**
 * Request provider service for VOP (Verification of Party) specific headers.
 * This service provides access to VOP-specific HTTP headers such as Digest, X-JWS-Signature,
 * Body-Sig-Profile, Body-Enc-Profile, Body-Enc-List, Accept-Language,
 * Client-Asynchronous-Process-Preferred, and API-Contract-ID.
 *
 * <p>These headers are used for:
 * <ul>
 *   <li>Message body signature verification (Digest, X-JWS-Signature, Body-Sig-Profile)</li>
 *   <li>Message body encryption (Body-Enc-Profile, Body-Enc-List)</li>
 *   <li>Language preferences (Accept-Language)</li>
 *   <li>Processing preferences (Client-Asynchronous-Process-Preferred)</li>
 *   <li>Commercial agreement identification (API-Contract-ID)</li>
 * </ul>
 */
@Service
@RequiredArgsConstructor
public class RequestVopProviderService {

    // Standard XS2A header constants
    private static final String X_REQUEST_ID_HEADER = "x-request-id";
    private static final String INSTANCE_ID = "instance-id";

    // VOP-specific header constants
    private static final String DIGEST_HEADER = "digest";
    private static final String X_JWS_SIGNATURE_HEADER = "x-jws-signature";
    private static final String BODY_SIG_PROFILE_HEADER = "body-sig-profile";
    private static final String BODY_ENC_PROFILE_HEADER = "body-enc-profile";
    private static final String BODY_ENC_LIST_HEADER = "body-enc-list";
    private static final String ACCEPT_LANGUAGE_HEADER = "accept-language";
    private static final String CLIENT_ASYNCHRONOUS_PROCESS_PREFERRED_HEADER = "client-asynchronous-process-preferred";
    private static final String API_CONTRACT_ID_HEADER = "api-contract-id";

    private final HttpServletRequest httpServletRequest;
    private final InternalRequestIdService internalRequestIdService;

    /**
     * Returns internal request ID that was assigned to the current request.
     * This ID is not provided by the TPP, instead it's being generated by the XS2A itself.
     *
     * @return internal request ID
     */
    @NotNull
    public UUID getInternalRequestId() {
        return internalRequestIdService.getInternalRequestId();
    }

    /**
     * Returns internal request ID as String.
     *
     * @return internal request ID as String
     */
    public String getInternalRequestIdString() {
        return getInternalRequestId().toString();
    }

    /**
     * Returns the X-Request-ID header value.
     *
     * @return UUID parsed from X-Request-ID header
     */
    public UUID getRequestId() {
        return UUID.fromString(getHeader(X_REQUEST_ID_HEADER));
    }

    /**
     * Returns the instance ID header value.
     *
     * @return instance ID header value, or null if not present
     */
    @Nullable
    public String getInstanceId() {
        return getHeader(INSTANCE_ID);
    }

    /**
     * Returns the value of the specified HTTP header.
     *
     * @param headerName the name of the header
     * @return the header value, or null if not present
     */
    private String getHeader(String headerName) {
        return httpServletRequest.getHeader(headerName);
    }

    public SigningHttpMessage getSigningHttpMessageData() {
        return new SigningHttpMessage(
            getDigest(),
            getXJwsSignature());
    }

    public SecuringBodyMessage getSecuringBodyMessageData() {
        return new SecuringBodyMessage(
            getBodySigProfile(),
            getBodyEncProfile(),
            getBodyEncList());
    }

    /**
     * Returns the Digest header value.
     * The Digest header contains a hash of the message body according to RFC3230.
     * If the message does not contain a body, the Digest header must contain the hash of an empty byte list.
     * Only SHA-256 and SHA-512 hash algorithms are supported as defined in RFC5843.
     *
     * @return Optional containing the Digest header value, or empty if not present
     */
    public Optional<String> getDigest() {
        return Optional.ofNullable(getHeader(DIGEST_HEADER));
    }

    /**
     * Returns the X-JWS-Signature header value.
     * The x-jws-signature header contains the JSON Web Signature for the request.
     *
     * @return Optional containing the X-JWS-Signature header value, or empty if not present
     */
    public Optional<String> getXJwsSignature() {
        return Optional.ofNullable(getHeader(X_JWS_SIGNATURE_HEADER));
    }

    /**
     * Returns the Body-Sig-Profile header value.
     * Indicates the signature profile used for signing (parts of) the body.
     * This header shall be used if the body is signed.
     *
     * @return Optional containing the Body-Sig-Profile header value, or empty if not present
     */
    public Optional<String> getBodySigProfile() {
        return Optional.ofNullable(getHeader(BODY_SIG_PROFILE_HEADER));
    }

    /**
     * Returns the Body-Enc-Profile header value.
     * Indicates the encryption profile used for the encryption of (parts of) the body.
     *
     * @return Optional containing the Body-Enc-Profile header value, or empty if not present
     */
    public Optional<String> getBodyEncProfile() {
        return Optional.ofNullable(getHeader(BODY_ENC_PROFILE_HEADER));
    }

    /**
     * Returns the Body-Enc-List header value.
     * Contains a list of names of data elements/attributes of the body which contain encrypted information.
     *
     * @return Optional containing the Body-Enc-List header value, or empty if not present
     */
    public Optional<String> getBodyEncList() {
        return Optional.ofNullable(getHeader(BODY_ENC_LIST_HEADER));
    }

    /**
     * Returns the Accept-Language header value.
     * The API Client may ask for a language for free text fields in the related response
     * (i.e. in additionalInformation). This header might be ignored by the ASPSP if the
     * addressed language is not supported. If not supported, the default language of the
     * ASPSP will be used.
     *
     * @return Optional containing the Accept-Language header value, or empty if not present
     */
    public Optional<String> getAcceptLanguageHeader() {
        return Optional.ofNullable(getHeader(ACCEPT_LANGUAGE_HEADER));
    }

    /**
     * Returns the Client-Asynchronous-Process-Preferred header value.
     * Indicates the client's preference for asynchronous or synchronous processing:
     * - true: Asynchronous process preferred
     * - false: Synchronous process preferred
     * The ASPSP may ignore this flag.
     *
     * @return Optional containing the Client-Asynchronous-Process-Preferred header value, or empty if not present
     */
    public Optional<Boolean> getClientAsynchronousProcessPreferred() {
        return Optional.ofNullable(getHeader(CLIENT_ASYNCHRONOUS_PROCESS_PREFERRED_HEADER))
                   .map(BooleanUtils::toBoolean);
    }

    /**
     * Returns the API-Contract-ID header value.
     * Might be mandated by the ASPSP if a commercial agreement is needed for the usage of the service.
     *
     * @return Optional containing the API-Contract-ID header value as UUID, or empty if not present
     */
    public Optional<UUID> getApiContractId() {
        return Optional.ofNullable(getHeader(API_CONTRACT_ID_HEADER))
                   .map(UUID::fromString);
    }

    /**
     * Returns the API-Contract-ID header value as String.
     * Might be mandated by the ASPSP if a commercial agreement is needed for the usage of the service.
     *
     * @return API-Contract-ID header value as String, or null if not present
     */
    @Nullable
    public String getApiContractIdString() {
        return getHeader(API_CONTRACT_ID_HEADER);
    }
}
