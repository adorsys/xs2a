package de.adorsys.psd2.xs2a.service.validator.vop;

import de.adorsys.psd2.xs2a.core.domain.TppMessageInformation;
import de.adorsys.psd2.xs2a.core.error.ErrorType;
import de.adorsys.psd2.xs2a.core.error.MessageErrorCode;
import de.adorsys.psd2.xs2a.core.profile.BulkVop;
import de.adorsys.psd2.xs2a.core.service.validator.ValidationResult;
import de.adorsys.psd2.xs2a.service.validator.BusinessValidator;
import de.adorsys.psd2.xs2a.service.validator.vop.dto.CreateVopRequestObject;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Component;

/**
 * Validator for bulk Verification of Payee (VOP) creation requests.
 *
 * <p>This validator ensures that the bulk party verification endpoint specified in the request
 * matches one of the valid {@link BulkVop} enumeration values. It validates that the endpoint
 * is supported by the system before proceeding with the bulk VOP operation.</p>
 *
 * <p>Valid bulk VOP endpoints include:</p>
 * <ul>
 *   <li>bulk-payee-verifications - For bulk payee verification</li>
 *   <li>bulk-payer-verifications - For bulk payer verification</li>
 *   <li>bulk-party-verifications - For general bulk party verification</li>
 * </ul>
 *
 * @see CreateVopValidator
 * @see BulkVop
 * @since 2025
 */
@Slf4j
@Component
public class CreateBulkVopValidator implements BusinessValidator<CreateVopRequestObject> {

    /**
     * Validates the bulk VOP creation request by checking if the bulkPartyVerificationEndpoint
     * matches a valid BulkVop enum value.
     *
     * <p>The validation follows these steps:</p>
     * <ol>
     *   <li>Extracts the bulkPartyVerificationEndpoint from the request object</li>
     *   <li>Validates that the endpoint is not null and matches a BulkVop enum value</li>
     *   <li>Returns a validation result indicating success or failure</li>
     * </ol>
     *
     * @param requestObject the VOP request object containing the bulk party verification endpoint
     * @return {@link ValidationResult#valid()} if the endpoint is valid,
     *         {@link ValidationResult#invalid(ErrorType, TppMessageInformation)} otherwise
     */
    @Override
    public ValidationResult validate(CreateVopRequestObject requestObject) {
        // Extract endpoint using the getter method generated by Lombok @Data
        String endpoint = requestObject != null
            ? requestObject.vopInitiationParameters().getBulkPartyVerificationEndpoint()
            : null;

        // Validate endpoint against BulkVop enum values
        if (endpoint != null && BulkVop.getByValue(endpoint).isPresent()) {
            return ValidationResult.valid();
        }

        return ValidationResult.invalid(
            ErrorType.VOP_400,
            TppMessageInformation.buildWithCustomError(
                MessageErrorCode.FORMAT_ERROR,
                "Unsupported bulkPartyVerificationEndpoint"
            )
        );
    }
}
